#!/usr/bin/env python3
"""Copy the shared verifier files into every task under eval/tasks.

Harbor uploads only a task's own tests/ directory into the sandbox, so shared
verifier code is vendored into each task. This script is the single writer of
those copies. Run it after editing anything under eval/verifier; run it with
--check in CI to fail on drift.

Per task it writes:
  environment/Dockerfile          from verifier/shared/Dockerfile
  tests/test.sh                   from verifier/shared/test.sh
  tests/consult_lib.py            from verifier/shared/consult_lib.py
  tests/consult_rules.py          from verifier/shared/consult_rules.py
  tests/reward.toml               from verifier/shared/reward.<kind>.toml
  tests/<dimension>/...           from verifier/shared/<dimension>/ (kind-dependent set)
  tests/hidden.mjs                from verifier/hidden/<task>.mjs (code tasks)
  tests/rules_probe.mjs           from verifier/hidden/<task>.rules.mjs (when present)
  tests/judge/instruction.md      from the task's instruction.md, or every step's
                                  instruction joined in order for a multi-step task

A multi-step task (task.toml [[steps]]) also gets its first step's verifier:
  steps/<first>/tests/test.sh                     from verifier/shared/brief_test.sh
  steps/<first>/tests/brief_suite/reward.toml     from verifier/shared/reward.brief.toml
  steps/<first>/tests/brief_suite/signoff/...     from verifier/shared/signoff/

Per-task files it never touches: task.toml, instruction.md, steps/*/instruction.md,
steps/*/solution/, environment/workspace, solution/, tests/consult.json,
tests/proof/submitted.py.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from itertools import chain
from pathlib import Path

EVAL_DIR = Path(__file__).resolve().parent.parent
TASKS_DIR = EVAL_DIR / "tasks"
SHARED_DIR = EVAL_DIR / "verifier" / "shared"
HIDDEN_DIR = EVAL_DIR / "verifier" / "hidden"
# task.toml step names; a regex, not tomllib, so CI's and macOS's python3 both run this.
STEP_NAME_RE = re.compile(r'^\[\[steps\]\]\s*\n\s*name\s*=\s*"([^"]+)"', re.MULTILINE)

COMMON_DIMENSIONS = ("skill_triggering", "non_interruption", "rules", "judge")
DIMENSIONS_BY_KIND = {
    "code": ("verification", "proof", "change_quality", *COMMON_DIMENSIONS),
    "routing": ("no_file_writes", *COMMON_DIMENSIONS),
}


def task_dirs() -> list[Path]:
    return sorted(p for p in TASKS_DIR.iterdir() if (p / "tests" / "consult.json").is_file())


def check_rule_ids(task: Path) -> None:
    """A rule id with no check would score 0 silently; fail the sync instead."""
    coverage = json.loads((EVAL_DIR / "verifier" / "rules.json").read_text())
    rules = json.loads((task / "tests" / "consult.json").read_text()).get("rules") or []
    unchecked = [r for r in rules if coverage.get(r) != "check"]
    if unchecked:
        raise SystemExit(f"{task.name}: consult.json rules without a check in rules.json: {', '.join(unchecked)}")


def task_kind(task: Path) -> str:
    kind = json.loads((task / "tests" / "consult.json").read_text()).get("kind")
    if kind not in DIMENSIONS_BY_KIND:
        raise SystemExit(f"{task.name}: consult.json kind must be one of {sorted(DIMENSIONS_BY_KIND)}, got {kind!r}")
    return kind


def step_names(task: Path) -> list[str]:
    return STEP_NAME_RE.findall((task / "task.toml").read_text())


def dimension_copies(dimension: str, dest_dir: Path) -> list[tuple[Path, Path]]:
    return [(source, dest_dir / source.name) for source in sorted((SHARED_DIR / dimension).iterdir()) if source.is_file()]


def judge_instruction(task: Path, steps: list[str]) -> Path | bytes:
    """The prompt the judge sees: the task instruction, or each step's instruction in order."""
    if not steps:
        return task / "instruction.md"
    parts = [f"## Turn {i}: {name}\n\n{(task / 'steps' / name / 'instruction.md').read_text().strip()}\n"
             for i, name in enumerate(steps, start=1)]
    return "\n".join(parts).encode()


def step_copies(task: Path, steps: list[str]) -> list[tuple[Path, Path]]:
    """The first step's own verifier: a sign-off suite scored apart from the root tests."""
    if not steps:
        return []
    step_tests = task / "steps" / steps[0] / "tests"
    suite = step_tests / "brief_suite"
    return [
        (SHARED_DIR / "brief_test.sh", step_tests / "test.sh"),
        (SHARED_DIR / "reward.brief.toml", suite / "reward.toml"),
        *dimension_copies("signoff", suite / "signoff"),
    ]


def planned_copies(task: Path) -> list[tuple[Path | bytes, Path]]:
    """(source file or generated bytes, destination) pairs for one task."""
    kind = task_kind(task)
    check_rule_ids(task)
    steps = step_names(task)
    tests = task / "tests"
    pairs: list[tuple[Path | bytes, Path]] = [
        (SHARED_DIR / "Dockerfile", task / "environment" / "Dockerfile"),
        (SHARED_DIR / "test.sh", tests / "test.sh"),
        (SHARED_DIR / "consult_lib.py", tests / "consult_lib.py"),
        (SHARED_DIR / "consult_rules.py", tests / "consult_rules.py"),
        (SHARED_DIR / f"reward.{kind}.toml", tests / "reward.toml"),
        (judge_instruction(task, steps), tests / "judge" / "instruction.md"),
        *step_copies(task, steps),
    ]
    for dimension in DIMENSIONS_BY_KIND[kind]:
        pairs.extend(dimension_copies(dimension, tests / dimension))
    if kind == "code":
        hidden = HIDDEN_DIR / f"{task.name}.mjs"
        if not hidden.is_file():
            raise SystemExit(f"{task.name}: missing hidden check {hidden}")
        pairs.append((hidden, tests / "hidden.mjs"))
    probe = HIDDEN_DIR / f"{task.name}.rules.mjs"
    if probe.is_file():
        pairs.append((probe, tests / "rules_probe.mjs"))
    return pairs


def source_bytes(source: Path | bytes) -> bytes:
    return source if isinstance(source, bytes) else source.read_bytes()


def write_copy(source: Path | bytes, dest: Path) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_bytes(source_bytes(source))
    if isinstance(source, Path):
        shutil.copymode(source, dest)
    print(f"synced {dest.relative_to(EVAL_DIR)}")


def sync(check: bool) -> int:
    drift: list[str] = []
    pairs = list(chain.from_iterable(planned_copies(task) for task in task_dirs()))
    for source, dest in pairs:
        if dest.is_file() and dest.read_bytes() == source_bytes(source):
            continue
        if check:
            drift.append(str(dest.relative_to(EVAL_DIR)))
            continue
        write_copy(source, dest)
    if drift:
        print("verifier files out of sync; run eval/scripts/sync_tests.py:", file=sys.stderr)
        for path in drift:
            print(f"  {path}", file=sys.stderr)
        return 1
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="report drift without writing")
    args = parser.parse_args()
    return sync(check=args.check)


if __name__ == "__main__":
    raise SystemExit(main())
